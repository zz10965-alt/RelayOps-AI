import {test,expect} from '@playwright/test';
import {startCase,runCase,showResult} from './support';
import {mkdirSync} from 'node:fs';

test('Chinese four-page redesign, truthful states, keyboard guidance and review screenshots',async({page})=>{
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://127.0.0.1:8003');
 const path='../docs/ui-redesign';mkdirSync(path,{recursive:true});
 const screenshot=async(name:string)=>{await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:`${path}/${name}.png`,fullPage:true,animations:'disabled'})};
 await expect(page.getByRole('heading',{name:/多模态电商运营智能体/})).toBeVisible();
 await expect(page.getByText('规划中',{exact:true})).toHaveCount(2);
 await expect(page.getByAltText('纸箱与紫色机器人装饰插画，非损坏证据')).toBeVisible();
 expect(await page.getByAltText('纸箱与紫色机器人装饰插画，非损坏证据').evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBeTruthy();
 await screenshot('01-home');
 await page.getByRole('button',{name:'开始体验商品损坏处理',exact:true}).click();
 await expect(page.getByRole('heading',{name:'第一步：选择业务场景'})).toBeVisible();
 await expect(page.getByRole('radio')).toHaveCount(4);
 await page.getByRole('radio').first().focus();await page.keyboard.press('ArrowDown');await expect(page.getByRole('radio').nth(1)).toBeChecked();
 await page.keyboard.press('ArrowUp');await expect(page.getByRole('radio').first()).toBeChecked();
 await page.getByRole('heading',{name:'第一步：选择业务场景'}).click();
 await screenshot('02-workflow');
 await page.getByRole('button',{name:'下一步：补充信息',exact:true}).click();
 await page.getByRole('button',{name:'生成演示订单',exact:true}).click();
 await page.getByLabel('问题描述').fill('模拟体验：白色陶瓷杯的杯身出现裂纹，希望申请售后。');
 await screenshot('02b-information');
 await runCase(page);
 await expect(page.locator('.agent-timeline .simulated')).toHaveCount(5);
 await page.getByRole('button',{name:'查看决策阶段',exact:true}).click();
 await expect(page.getByRole('heading',{name:'当前查看：决策'})).toBeVisible();
 await screenshot('03-execution');
 await showResult(page);
 await expect(page.getByRole('heading',{name:'已创建模拟退货申请',exact:true})).toBeVisible();
 await expect(page.locator('.boundary-note').first()).toContainText('不是模型、API或SQLite执行证明');
 await screenshot('04-result');
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();await screenshot('06-mobile-result');
 await page.getByRole('button',{name:'查看完整执行过程',exact:true}).click();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();await screenshot('07-mobile-execution');
 await page.setViewportSize({width:1440,height:1000});
 await startCase(page,'expired');await page.getByRole('button',{name:'生成演示订单',exact:true}).click();await page.getByLabel('问题描述').fill('模拟体验：核查超出售后期限的订单。');await runCase(page);
 await expect(page.locator('.agent-timeline li.not_observed')).toHaveCount(2);await showResult(page);
 await expect(page.getByRole('heading',{name:'需要人工核查',exact:true})).toBeVisible();
 await expect(page.locator('.resolution')).toContainText('30天售后期限');
 await screenshot('05-handoff');
});
